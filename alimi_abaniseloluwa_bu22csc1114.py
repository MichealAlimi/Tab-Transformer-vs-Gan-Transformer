# ============================================================
# STEP 2: IMPORT LIBRARIES
# ============================================================
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import shap
import torch
import warnings
warnings.filterwarnings('ignore')

from sklearn.model_selection import StratifiedKFold, train_test_split
from sklearn.preprocessing import LabelEncoder
from sklearn.metrics import (accuracy_score, precision_score, recall_score,
    f1_score, roc_auc_score, matthews_corrcoef,
    confusion_matrix, classification_report, roc_curve, auc)
from imblearn.over_sampling import SMOTE
from ctgan import CTGAN
from pytorch_tabular import TabularModel
from pytorch_tabular.models import TabTransformerConfig
from pytorch_tabular.config import DataConfig, OptimizerConfig, TrainerConfig

SEED = 42
np.random.seed(SEED)
torch.manual_seed(SEED)
print("Libraries imported successfully.")
print(f"GPU available: {torch.cuda.is_available()}")

# ============================================================
# STEP 3: UPLOAD AND LOAD DATASET
# ============================================================
from google.colab import files
uploaded = files.upload()

filename = list(uploaded.keys())[0]
df = pd.read_excel(filename, engine='xlrd')

print(f"Dataset loaded: {filename}")
print(f"Shape: {df.shape}")
print(f"\nPerformanceRating distribution:")
print(df['PerformanceRating'].value_counts().sort_index())

# ============================================================
# STEP 4: BINARY TARGET ENGINEERING AND SMOTE BALANCING
# ============================================================
# Binary target: Rating 4 = High Performance (1), else Low (0)
df['PerformanceBinary'] = df['PerformanceRating'].apply(
    lambda x: 1 if x == 4 else 0)
TARGET = 'PerformanceBinary'

print("Binary distribution BEFORE SMOTE:")
print(df[TARGET].value_counts())

# Drop unnecessary columns
cols_to_drop = [c for c in ['PerformanceRating', 'Attrition', 'EmpNumber']
                if c in df.columns]
X = df.drop(columns=cols_to_drop + [TARGET])
y = df[TARGET].copy()

# Identify feature types
CAT_COLS = X.select_dtypes(include=['object', 'category']).columns.tolist()
NUM_COLS = X.select_dtypes(include=['int64', 'float64']).columns.tolist()
for col in CAT_COLS:
    X[col] = X[col].astype(str)

print(f"\nCategorical features ({len(CAT_COLS)}): {CAT_COLS}")
print(f"Numerical features  ({len(NUM_COLS)}): {NUM_COLS}")

# Encode for SMOTE
X_encoded = X.copy()
le_dict = {}
for col in CAT_COLS:
    le = LabelEncoder()
    X_encoded[col] = le.fit_transform(X[col])
    le_dict[col] = le

# Apply SMOTE
smote = SMOTE(random_state=SEED, sampling_strategy=1.0)
X_res, y_res = smote.fit_resample(X_encoded, y)

# Decode back to original categorical values
for col in CAT_COLS:
    X_res[col] = le_dict[col].inverse_transform(
        X_res[col].astype(int)).astype(str)

X = X_res.reset_index(drop=True)
y = pd.Series(y_res).reset_index(drop=True)

print(f"\nClass distribution AFTER SMOTE:")
print(y.value_counts())
print(f"Total samples: {len(X)}")

# ============================================================
# STEP 5: TRAIN/TEST SPLIT
# ============================================================
X_trainval, X_test, y_trainval, y_test = train_test_split(
    X, y, test_size=0.15, random_state=SEED, stratify=y)

print(f"Train+Val : {len(X_trainval)} samples")
print(f"Test set  : {len(X_test)} samples")
print(f"\nTest class balance:")
print(y_test.value_counts())
print("Data preparation complete.")

# ============================================================
# STEP 6: MODEL 1 — TABTRANSFORMER 5-FOLD CROSS VALIDATION
# ============================================================
skf = StratifiedKFold(n_splits=5, shuffle=True, random_state=SEED)
tab_metrics = {'accuracy':[], 'precision':[], 'recall':[],
               'f1':[], 'auc':[], 'mcc':[]}

print('='*60)
print('MODEL 1: TabTransformer - 5-Fold Cross Validation')
print('='*60)

for fold, (train_idx, val_idx) in enumerate(skf.split(X_trainval, y_trainval)):
    print(f'\nFold {fold+1}/5...')
    X_tr = X_trainval.iloc[train_idx].reset_index(drop=True)
    y_tr = y_trainval.iloc[train_idx].reset_index(drop=True)
    X_val = X_trainval.iloc[val_idx].reset_index(drop=True)
    y_val = y_trainval.iloc[val_idx].reset_index(drop=True)

    train_df = X_tr.copy(); train_df[TARGET] = y_tr.values
    val_df = X_val.copy(); val_df[TARGET] = y_val.values

    data_config = DataConfig(
        target=[TARGET],
        continuous_cols=NUM_COLS,
        categorical_cols=CAT_COLS)

    trainer_config = TrainerConfig(
        auto_lr_find=False,
        batch_size=32,
        max_epochs=200,
        early_stopping='valid_loss',
        early_stopping_patience=20,
        checkpoints='valid_loss',
        load_best=True,
        progress_bar='none',
        trainer_kwargs={'enable_model_summary': False})

    optimizer_config = OptimizerConfig(
        optimizer='AdamW',
        optimizer_params={'weight_decay': 1e-4},
        lr_scheduler='CosineAnnealingWarmRestarts',
        lr_scheduler_params={'T_0': 50, 'T_mult': 2})

    model_config = TabTransformerConfig(
        task='classification',
        input_embed_dim=64,
        num_heads=8,
        num_attn_blocks=8,
        ff_hidden_multiplier=4,
        attn_dropout=0.1,
        ff_dropout=0.1,
        learning_rate=3e-4,
        metrics=['accuracy'])

    model = TabularModel(
        data_config=data_config,
        model_config=model_config,
        optimizer_config=optimizer_config,
        trainer_config=trainer_config,
        verbose=False)

    model.fit(train=train_df, validation=val_df)

    preds = model.predict(X_val)
    pred_col = [c for c in preds.columns if 'prediction' in c.lower()][0]
    y_pred = preds[pred_col].values.astype(int)
    prob_cols = [c for c in preds.columns if '1' in c and 'probability' in c.lower()]
    y_prob = preds[prob_cols[0]].values if prob_cols else y_pred

    tab_metrics['accuracy'].append(accuracy_score(y_val, y_pred))
    tab_metrics['precision'].append(precision_score(y_val, y_pred, zero_division=0))
    tab_metrics['recall'].append(recall_score(y_val, y_pred, zero_division=0))
    tab_metrics['f1'].append(f1_score(y_val, y_pred, zero_division=0))
    tab_metrics['auc'].append(roc_auc_score(y_val, y_prob))
    tab_metrics['mcc'].append(matthews_corrcoef(y_val, y_pred))

    print(f'  Accuracy: {tab_metrics["accuracy"][-1]:.4f} | '
          f'AUC: {tab_metrics["auc"][-1]:.4f}')

    if fold == 4:
        tab_model_final = model
        X_val_final = X_val.copy()

print('\n' + '='*60)
print('TABTRANSFORMER CROSS-VALIDATION RESULTS')
print('='*60)
for m, v in tab_metrics.items():
    print(f'{m:12s}: {np.mean(v):.4f} +/- {np.std(v):.4f}')

# ============================================================
# STEP 7: TABTRANSFORMER FINAL TEST SET EVALUATION
# ============================================================
test_preds = tab_model_final.predict(X_test)
pred_col = [c for c in test_preds.columns if 'prediction' in c.lower()][0]
y_test_pred_tab = test_preds[pred_col].values.astype(int)
prob_cols = [c for c in test_preds.columns if '1' in c and 'probability' in c.lower()]
y_test_prob_tab = test_preds[prob_cols[0]].values if prob_cols else y_test_pred_tab

print('='*60)
print('TABTRANSFORMER - FINAL TEST SET RESULTS')
print('='*60)
print(f'Accuracy : {accuracy_score(y_test, y_test_pred_tab):.4f}')
print(f'Precision: {precision_score(y_test, y_test_pred_tab, zero_division=0):.4f}')
print(f'Recall   : {recall_score(y_test, y_test_pred_tab, zero_division=0):.4f}')
print(f'F1-Score : {f1_score(y_test, y_test_pred_tab, zero_division=0):.4f}')
print(f'ROC-AUC  : {roc_auc_score(y_test, y_test_prob_tab):.4f}')
print(f'MCC      : {matthews_corrcoef(y_test, y_test_pred_tab):.4f}')
print('\nClassification Report:')
print(classification_report(y_test, y_test_pred_tab,
      target_names=['Low Performance', 'High Performance']))

# Confusion Matrix
cm_tab = confusion_matrix(y_test, y_test_pred_tab)
plt.figure(figsize=(6, 5))
sns.heatmap(cm_tab, annot=True, fmt='d', cmap='Blues',
            xticklabels=['Low', 'High'],
            yticklabels=['Low', 'High'],
            linewidths=1, linecolor='white')
plt.title('TabTransformer Confusion Matrix', fontsize=13, fontweight='bold')
plt.ylabel('Actual')
plt.xlabel('Predicted')
plt.tight_layout()
plt.savefig('figure_3_tabtransformer_confusion_matrix.png', bbox_inches='tight')
plt.show()

