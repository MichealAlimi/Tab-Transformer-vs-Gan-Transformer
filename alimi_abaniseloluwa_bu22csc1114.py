    y_prob = preds[prob_cols[0]].values if prob_cols else y_pred

    gan_metrics['accuracy'].append(accuracy_score(y_val, y_pred))
    gan_metrics['precision'].append(precision_score(y_val, y_pred, zero_division=0))
    gan_metrics['recall'].append(recall_score(y_val, y_pred, zero_division=0))
    gan_metrics['f1'].append(f1_score(y_val, y_pred, zero_division=0))
    gan_metrics['auc'].append(roc_auc_score(y_val, y_prob))
    gan_metrics['mcc'].append(matthews_corrcoef(y_val, y_pred))

    print(f'  Accuracy: {gan_metrics["accuracy"][-1]:.4f} | '
          f'AUC: {gan_metrics["auc"][-1]:.4f}')

    if fold == 4:
        gan_model_final = gan_model
