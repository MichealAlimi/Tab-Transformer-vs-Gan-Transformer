print('Running SHAP analysis for TabTransformer...')

def tab_predict_proba(data_array):
    df_input = pd.DataFrame(data_array, columns=X.columns)
    for col in CAT_COLS:
        df_input[col] = df_input[col].astype(str)
    for col in NUM_COLS:
        if col in df_input.columns:
            df_input[col] = pd.to_numeric(df_input[col], errors='coerce').fillna(0)
    preds = tab_model_final.predict(df_input)
    prob_cols = [c for c in preds.columns if 'probability' in c.lower()]
    if prob_cols:
        return preds[prob_cols].values
    return np.column_stack([1-preds.iloc[:,0].values, preds.iloc[:,0].values])

background = X_val_final.iloc[:50].values.astype(str)
explainer_tab = shap.KernelExplainer(tab_predict_proba, background)
shap_values_tab = explainer_tab.shap_values(
    X_val_final.iloc[:100].values.astype(str), nsamples=100)

sv_tab = np.array(shap_values_tab)[:,:,1]
X_shap = X_val_final.iloc[:100].reset_index(drop=True)

plt.figure(figsize=(10, 7))
shap.summary_plot(sv_tab, X_shap, feature_names=X.columns.tolist(),
    plot_type='bar', show=False, color='steelblue')
plt.title('TabTransformer - SHAP Global Feature Importance',
          fontsize=13, fontweight='bold')
plt.tight_layout()
plt.savefig('figure_4_shap_tabtransformer_global.png', bbox_inches='tight')
plt.show()

plt.figure(figsize=(10, 7))
shap.summary_plot(sv_tab, X_shap, feature_names=X.columns.tolist(), show=False)
plt.title('TabTransformer - SHAP Beeswarm Plot', fontsize=13, fontweight='bold')
plt.tight_layout()
plt.savefig('figure_5_shap_tabtransformer_beeswarm.png', bbox_inches='tight')
plt.show()

mean_importance = np.abs(sv_tab).mean(axis=0).flatten()
min_len = min(len(X.columns.tolist()), len(mean_importance))
tab_feature_importance = pd.DataFrame({
    'Feature': X.columns.tolist()[:min_len],
    'SHAP_Importance': mean_importance[:min_len]
}).sort_values('SHAP_Importance', ascending=False)

print('TabTransformer SHAP analysis complete.')
print('\nTop 10 Features (TabTransformer):')
