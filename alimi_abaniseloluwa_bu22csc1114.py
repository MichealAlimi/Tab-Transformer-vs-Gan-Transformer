discrete_cols = CAT_COLS + [TARGET]

ctgan = CTGAN(
    epochs=300,
    batch_size=500,
    generator_dim=(256, 256),
    discriminator_dim=(256, 256),
    pac=10,
    verbose=True)

print('Training CTGAN...')
ctgan.fit(train_for_gan, discrete_columns=discrete_cols)
synthetic_data = ctgan.sample(len(X_trainval))

syn_high = synthetic_data[synthetic_data[TARGET]==1]
syn_low = synthetic_data[synthetic_data[TARGET]==0]
syn_low_up = syn_low.sample(n=len(syn_high), replace=True, random_state=SEED)
synthetic_data = pd.concat([syn_high, syn_low_up],
    ignore_index=True).sample(frac=1, random_state=SEED).reset_index(drop=True)

syn_X = synthetic_data.drop(columns=[TARGET])
syn_y = synthetic_data[TARGET]
for col in CAT_COLS:
    if col in syn_X.columns:
        syn_X[col] = syn_X[col].astype(str)

print(f'Generated {len(synthetic_data)} synthetic records.')
